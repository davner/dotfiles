CREDIT="$DIR/home/.claude/hooks/ai-credit.sh"
credit_table() { # name, function; cases as `want|text` on stdin, \n escapes in text
  local want text t got
  while IFS='|' read -r want text; do
    [ -n "$text" ] || continue
    printf -v t '%b' "$text"
    # shellcheck source=/dev/null
    (source "$CREDIT" && "$2" "$t") </dev/null
    got=$?
    want_exit "$1: $text" "$want" "$got"
  done
}

